def make_liaw_model_16(device, dtype=np.float32):
    """Create a 16-batch LiawModel using init_pop_01 parameters."""
    from lpf.models import LiawModel
    from lpf.initializers import LiawInitializer

    model = LiawModel(
        initializer=LiawInitializer(
            init_states=LIAW_INIT_STATES_16.astype(dtype),
            init_pts=LIAW_INIT_PTS_16,
        ),
        n_init_pts=LIAW_N_INIT_PTS_16,
        params=LIAW_PARAMS_16.astype(dtype),
        thr_color=0.5 * np.ones((LIAW_BATCH_SIZE_16, 1, 1)),
        width=LIAW_WIDTH_16, height=LIAW_HEIGHT_16, dx=LIAW_DX,
        device=device, dtype=dtype,
    )
    model.initialize()
    return model


def get_numpy(model):
    """Extract y_mesh as numpy regardless of backend."""
    arr = model.y_mesh
    if hasattr(arr, 'get'):
        return arr.get()
    if hasattr(arr, 'cpu'):
        return arr.detach().cpu().numpy()
    return np.asarray(arr)


